// Deterministic public catalog seed: no network, credentials or user records.
import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
const bundle = await build({
  stdin: {
    contents:
      "export { INITIAL_FOOD_ITEMS,INITIAL_RECIPES } from './src/data/seedData'; export { OPENGYM_EXERCISE_CATALOG } from './src/data/opengymCatalog';",
    resolveDir: process.cwd(),
  },
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'node',
});
const {
  INITIAL_FOOD_ITEMS: foods,
  INITIAL_RECIPES: recipes,
  OPENGYM_EXERCISE_CATALOG: exercises,
} = await import(
  `data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`
);
const quote = (v) =>
  v == null
    ? 'NULL'
    : typeof v === 'number'
      ? String(v)
      : typeof v === 'boolean'
        ? v
          ? 'TRUE'
          : 'FALSE'
        : `'${String(v).replaceAll("'", "''")}'`;
const lines = ['-- Generated by node scripts/generate-seed.mjs; do not edit.', 'BEGIN;'];
function insert(table, columns, values) {
  lines.push(
    `INSERT INTO ${table} (${columns.join(',')}) VALUES (${values.map(quote).join(',')}) ON CONFLICT DO NOTHING;`,
  );
}
for (const f of foods)
  insert(
    'food_items',
    [
      'id',
      'name',
      'brand',
      'kcal_per_100g',
      'protein_per_100g',
      'carbs_per_100g',
      'fat_per_100g',
      'fiber_per_100g',
      'default_serving_name',
      'default_serving_grams',
      'is_bridge_food',
    ],
    [
      f.id,
      f.name,
      f.brand,
      f.kcalPer100g,
      f.proteinPer100g,
      f.carbsPer100g,
      f.fatPer100g,
      f.fiberPer100g ?? 0,
      f.defaultServingName,
      f.defaultServingGrams,
      !!f.isBridgeFood,
    ],
  );
for (const r of recipes) {
  insert('recipes', ['id', 'name'], [r.id, r.name]);
  for (const i of r.ingredients)
    insert('recipe_ingredients', ['recipe_id', 'food_id', 'grams'], [r.id, i.foodId, i.grams]);
}
for (const ex of exercises) {
  insert('equipment_types', ['id', 'name_es'], [ex.equipment, ex.equipment]);
  for (const m of [ex.primaryMuscle, ...ex.secondaryMuscles])
    insert('muscle_groups', ['id', 'name_es'], [m, m]);
  insert(
    'exercise_catalog_items',
    ['id', 'name_es', 'name_en', 'equipment_id', 'category_id', 'is_unilateral'],
    [ex.id, ex.nameEs, ex.nameEn, ex.equipment, ex.category, !!ex.isUnilateral],
  );
  insert(
    'exercise_muscle_groups',
    ['exercise_id', 'muscle_group_id', 'involvement_role'],
    [ex.id, ex.primaryMuscle, 'primary'],
  );
  for (const m of ex.secondaryMuscles)
    insert(
      'exercise_muscle_groups',
      ['exercise_id', 'muscle_group_id', 'involvement_role'],
      [ex.id, m, 'secondary'],
    );
  ex.instructionsEs.forEach((text, i) =>
    insert(
      'exercise_instructions',
      ['exercise_id', 'step_number', 'instruction_es'],
      [ex.id, i + 1, text],
    ),
  );
  ex.images.forEach((url, i) =>
    insert('exercise_images', ['exercise_id', 'image_order', 'image_url'], [ex.id, i, url]),
  );
  ex.aliases.forEach((text) =>
    insert('exercise_aliases', ['exercise_id', 'alias_text'], [ex.id, text]),
  );
}
lines.push('COMMIT;', '');
await writeFile('supabase/seed.sql', lines.join('\n'));
